//! vortex-ui/src/font.rs
//! Complete 95-character printable ASCII 6x10 bitmap typography renderer.

pub struct Font;

pub const CHAR_W: i32 = 7;
pub const CHAR_H: i32 = 10;

impl Font {
    pub fn measure_width(text: &str) -> i32 {
        (text.chars().filter(|&c| c != '\n').count() as i32) * CHAR_W
    }

    pub fn draw_text(surface: &mut [u32], surf_w: usize, surf_h: usize, x: i32, y: i32, text: &str, color: u32) {
        if surface.is_empty() || surf_w == 0 || surf_h == 0 {
            return;
        }

        let mut cur_x = x;
        for ch in text.chars() {
            if ch == '\n' {
                continue;
            }
            Self::draw_char(surface, surf_w, surf_h, cur_x, y, ch, color);
            cur_x += CHAR_W;
        }
    }

    pub fn draw_text_max_width(
        surface: &mut [u32],
        surf_w: usize,
        surf_h: usize,
        x: i32,
        y: i32,
        text: &str,
        max_px: i32,
        color: u32,
    ) {
        if max_px <= CHAR_W {
            return;
        }
        let max_chars = (max_px / CHAR_W) as usize;
        let count = text.chars().count();
        if count <= max_chars {
            Self::draw_text(surface, surf_w, surf_h, x, y, text, color);
        } else if max_chars > 3 {
            let mut truncated: String = text.chars().take(max_chars - 3).collect();
            truncated.push_str("...");
            Self::draw_text(surface, surf_w, surf_h, x, y, &truncated, color);
        } else {
            let truncated: String = text.chars().take(max_chars).collect();
            Self::draw_text(surface, surf_w, surf_h, x, y, &truncated, color);
        }
    }

    pub fn draw_char(surface: &mut [u32], surf_w: usize, surf_h: usize, x: i32, y: i32, ch: char, color: u32) {
        let glyph = get_glyph(ch);
        for row in 0..10 {
            let py = y + row;
            if py < 0 || py >= surf_h as i32 {
                continue;
            }
            let bits = glyph[row as usize];
            for col in 0..6 {
                let px = x + col;
                if px < 0 || px >= surf_w as i32 {
                    continue;
                }
                if (bits & (1 << (5 - col))) != 0 {
                    let idx = (py as usize) * surf_w + (px as usize);
                    if idx < surface.len() {
                        surface[idx] = color;
                    }
                }
            }
        }
    }
}

